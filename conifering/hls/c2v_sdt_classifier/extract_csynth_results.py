#!/usr/bin/env python3
"""
extract_csynth_results.py <sweep_dir> [output_csv]

Scans <sweep_dir> for directories named my_prj_depth_N/ containing
solution1/syn/report/my_prj_csynth.xml, parses each report, and writes
one row per depth to a CSV.

Usage:
    python3 extract_csynth_results.py conifering/hls/c2v_event_classifier results.csv

Generated by claude.ai/
"""
import re
import sys
import csv
import xml.etree.ElementTree as ET
from pathlib import Path


def text_or_none(root, path, cast=str):
    if root is None:
        return None
    el = root.find(path)
    if el is None or el.text is None:
        return None
    try:
        return cast(el.text.strip())
    except ValueError:
        return el.text.strip()


def parse_csynth_xml(path: Path) -> dict:
    tree = ET.parse(path)
    root = tree.getroot()

    out = {}

    # --- Timing ---
    target_clk = text_or_none(root, "./UserAssignments/TargetClockPeriod", float)
    est_clk = text_or_none(root, "./PerformanceEstimates/SummaryOfTimingAnalysis/EstimatedClockPeriod", float)
    out["clock_target_ns"] = target_clk
    out["clock_estimated_ns"] = est_clk
    out["fmax_mhz"] = round(1000.0 / est_clk, 2) if est_clk else None

    # --- Latency / Interval ---
    lat = root.find("./PerformanceEstimates/SummaryOfOverallLatency")
    if lat is not None:
        out["latency_min_cycles"] = text_or_none(lat, "Best-caseLatency", int)
        out["latency_max_cycles"] = text_or_none(lat, "Worst-caseLatency", int)
        out["latency_min_ns"] = text_or_none(lat, "Best-caseRealTimeLatency",
                                              lambda s: float(s.replace(" ns", "")))
        out["latency_max_ns"] = text_or_none(lat, "Worst-caseRealTimeLatency",
                                              lambda s: float(s.replace(" ns", "")))
        #out["latency_max_ns_at_fmax"] = round(out["latency_max_cycles"] * est_clk, 3) if out["latency_max_cycles"] and est_clk else None        
        out["II_min"] = text_or_none(lat, "Interval-min", int)
        out["II_max"] = text_or_none(lat, "Interval-max", int)
        out["pipeline_depth"] = text_or_none(lat, "PipelineDepth", int)
    else:
        for k in ["latency_min_cycles", "latency_max_cycles", "latency_min_ns",
                   "latency_max_ns", "II_min", "II_max", "pipeline_depth"]:
            out[k] = None
    out["pipeline_type"] = text_or_none(root, "./PerformanceEstimates/PipelineType")

    # --- Utilization ---
    res = root.find("./AreaEstimates/Resources")
    avail = root.find("./AreaEstimates/AvailableResources")
    for tag in ["BRAM_18K", "DSP", "FF", "LUT", "URAM"]:
        used = text_or_none(res, tag, int) if res is not None else None
        total = text_or_none(avail, tag, int) if avail is not None else None
        out[tag] = used
        out[f"{tag}_available"] = total
        out[f"{tag}_pct"] = round(100.0 * used / total, 3) if used is not None and total else None

    return out


def main():
    if len(sys.argv) < 2:
        print("usage: extract_csynth_results.py <sweep_dir> [output_csv]")
        sys.exit(1)

    sweep_dir = Path(sys.argv[1])
    out_csv = Path(sys.argv[2]) if len(sys.argv) > 2 else sweep_dir / "results.csv"

    depth_dirs = sorted(
        sweep_dir.glob("my_prj_depth_*"),
        key=lambda p: int(re.search(r"depth_(\d+)", p.name).group(1)),
    )

    if not depth_dirs:
        print(f"No my_prj_depth_* directories found under {sweep_dir}")
        sys.exit(1)

    rows = []
    fieldnames = ["depth", "clock_target_ns", "clock_estimated_ns", "fmax_mhz",
                  "latency_min_cycles", "latency_max_cycles", "latency_min_ns",
                  "latency_max_ns", "II_min", "II_max", "pipeline_depth", "pipeline_type",
                  "BRAM_18K", "BRAM_18K_available", "BRAM_18K_pct",
                  "DSP", "DSP_available", "DSP_pct",
                  "FF", "FF_available", "FF_pct",
                  "LUT", "LUT_available", "LUT_pct",
                  "URAM", "URAM_available", "URAM_pct"]

    for d in depth_dirs:
        depth = int(re.search(r"depth_(\d+)", d.name).group(1))
        xml_path = d / "solution1" / "syn" / "report" / "my_prj_csynth.xml"
        if not xml_path.exists():
            print(f"WARNING: no report at {xml_path}, skipping depth {depth}")
            continue
        parsed = parse_csynth_xml(xml_path)
        parsed["depth"] = depth
        rows.append(parsed)
        print(f"depth {depth}: LUT={parsed['LUT']} FF={parsed['FF']} "
              f"DSP={parsed['DSP']} BRAM={parsed['BRAM_18K']} "
              f"Fmax={parsed['fmax_mhz']}MHz latency={parsed['latency_max_cycles']}cyc")

    rows.sort(key=lambda r: r["depth"])

    with open(out_csv, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    print(f"\nwrote {len(rows)} rows to {out_csv}")


if __name__ == "__main__":
    main()